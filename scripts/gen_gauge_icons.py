#!/usr/bin/env python3
"""
Draws the fuel-pump and coolant-thermometer gauge icons and writes them as
LVGL 8 LV_IMG_CF_ALPHA_8BIT images (alpha only), so the UI can tint them any
color with img_recolor (dial color normally, yellow for warnings).

Usage: python3 gen_gauge_icons.py OUT_DIR [SIZE]
"""
import sys, math
from PIL import Image, ImageDraw

SS = 4  # supersampling


def canvas(n):
    im = Image.new("L", (n * SS, n * SS), 0)
    return im, ImageDraw.Draw(im)


def s(v):
    return [int(x * SS) for x in v] if isinstance(v, (list, tuple)) else int(v * SS)


def fuel_pump(n=40):
    # Drawn on a 40x40 grid
    im, d = canvas(n)
    d.rounded_rectangle(s((5, 4, 23, 35)), radius=s(2), fill=255)           # body
    d.rectangle(s((8, 8, 20, 16)), fill=0)                                   # window
    d.rectangle(s((2, 34, 26, 37)), fill=255)                                # base
    hose = [(23, 23), (27, 23), (27, 31), (30, 32), (33, 30), (33, 13), (29, 8)]
    d.line([s(p) for p in hose], fill=255, width=s(2.6), joint="curve")
    d.line([s((29, 8)), s((26, 5))], fill=255, width=s(3.2))                 # nozzle
    return im.resize((n, n), Image.LANCZOS)


def coolant(n=40):
    im, d = canvas(n)
    # thermometer stem + bulb
    d.rounded_rectangle(s((17.5, 2, 22.5, 24)), radius=s(2.5), fill=255)
    d.ellipse(s((15, 21, 25, 31)), fill=255)
    for y, l in ((6, 6), (11, 4), (16, 6)):                                  # scale ticks
        d.line([s((24.5, y)), s((24.5 + l, y))], fill=255, width=s(2))
    # two waves
    for y0 in (31.5, 36.5):
        pts = [(x, y0 + 1.6 * math.sin((x - 2) / 36 * 4 * math.pi)) for x in [2 + i * 0.5 for i in range(73)]]
        d.line([s(p) for p in pts], fill=255, width=s(2.2), joint="curve")
    return im.resize((n, n), Image.LANCZOS)


def write(im, name, out_dir):
    w, h = im.size
    px = list(im.getdata())
    with open(f"{out_dir}/{name}.c", "w") as f:
        f.write(f"""// {name}: {w}x{h} alpha-only gauge icon, generated by scripts/gen_gauge_icons.py
#ifdef __has_include
    #if __has_include("lvgl.h")
        #ifndef LV_LVGL_H_INCLUDE_SIMPLE
            #define LV_LVGL_H_INCLUDE_SIMPLE
        #endif
    #endif
#endif
#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

static const LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
""")
        for i in range(0, len(px), 20):
            f.write("    " + ", ".join(f"0x{v:02x}" for v in px[i:i + 20]) + ",\n")
        f.write(f"""}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_ALPHA_8BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {w * h},
    .data = {name}_map,
}};
""")


if __name__ == "__main__":
    out = sys.argv[1]
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 40
    write(fuel_pump(n), "ui_icon_fuel", out)
    write(coolant(n), "ui_icon_coolant", out)
    print("icons written to", out)
